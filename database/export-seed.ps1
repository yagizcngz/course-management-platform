# Regenerates database/seed-demo.sql from a freshly seeded throwaway database.
#
#   1. Seed an empty database with a known demo password (the API applies migrations itself):
#        cd backend/EdTechApi.API
#        $env:ASPNETCORE_ENVIRONMENT='Development'
#        $env:ConnectionStrings__DefaultConnection='Server=localhost\SQLEXPRESS;Database=EdTechSeedExport;Trusted_Connection=True;TrustServerCertificate=True;'
#        $env:Seed__DemoUsers='true'; $env:Seed__DemoPassword='Demo-2026!'
#        dotnet run --no-launch-profile -- --seed-only
#   2. powershell -File database/export-seed.ps1 -Server 'localhost\SQLEXPRESS' -Database EdTechSeedExport
#
# Never point it at a database with real users: every row is written out.
param(
    [string]$Server = 'localhost\SQLEXPRESS',
    [string]$Database = 'EdTechSeedExport',
    [string]$Out = (Join-Path $PSScriptRoot 'seed-demo.sql')
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

# parents before children, so foreign keys hold while inserting
$tables = 'Categories', 'SystemSettings', 'Announcements', 'Users', 'Teachers', 'Students', 'Courses', 'Lessons',
    'Enrollments', 'LessonCompletions', 'WalletTransactions', 'TeacherApplications', 'TeachingRequests',
    'SupportRequests', 'ForumThreads', 'ForumPosts', 'ForumPostLikes', 'Friendships', 'DirectMessages'

$conn = New-Object System.Data.SqlClient.SqlConnection "Server=$Server;Database=$Database;Integrated Security=True;TrustServerCertificate=True"
$conn.Open()

function Literal($v) {
    if ($v -is [System.DBNull] -or $null -eq $v) { return 'NULL' }
    if ($v -is [bool]) { if ($v) { return '1' } else { return '0' } }
    if ($v -is [datetime]) { return "'" + $v.ToString('yyyy-MM-ddTHH:mm:ss.fffffff') + "'" }
    if ($v -is [decimal] -or $v -is [double] -or $v -is [single]) { return $v.ToString([System.Globalization.CultureInfo]::InvariantCulture) }
    if ($v -is [int] -or $v -is [long] -or $v -is [int16] -or $v -is [byte]) { return "$v" }
    return "N'" + ([string]$v).Replace("'", "''") + "'"
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('-- E-Kurs demo data. Generated by database/export-seed.ps1; do not edit by hand.')
[void]$sb.AppendLine('-- Demo accounts: demo_admin, demo_teacher, demo_student; password: Demo-2026! (development only).')
[void]$sb.AppendLine("IF NOT EXISTS (SELECT 1 FROM [Users] WHERE [Username] = N'demo_admin')")
[void]$sb.AppendLine('BEGIN')
[void]$sb.AppendLine('SET NOCOUNT ON;')
[void]$sb.AppendLine('BEGIN TRANSACTION;')
foreach ($t in $tables) {
    $idCmd = $conn.CreateCommand()
    $idCmd.CommandText = "SELECT OBJECTPROPERTY(OBJECT_ID(N'[$t]'), 'TableHasIdentity')"
    $identity = [int]$idCmd.ExecuteScalar() -eq 1
    $cmd = $conn.CreateCommand()
    $cmd.CommandText = "SELECT * FROM [$t] ORDER BY 1"
    $reader = $cmd.ExecuteReader()
    $cols = 0..($reader.FieldCount - 1) | ForEach-Object { '[' + $reader.GetName($_) + ']' }
    $rows = New-Object System.Collections.Generic.List[string]
    while ($reader.Read()) {
        $vals = 0..($reader.FieldCount - 1) | ForEach-Object { Literal $reader.GetValue($_) }
        $rows.Add('(' + ($vals -join ', ') + ')')
    }
    $reader.Close()
    if ($rows.Count -eq 0) { continue }
    [void]$sb.AppendLine("-- $t ($($rows.Count))")
    if ($identity) { [void]$sb.AppendLine("SET IDENTITY_INSERT [$t] ON;") }
    # SQL Server takes at most 1000 rows per VALUES list
    for ($i = 0; $i -lt $rows.Count; $i += 500) {
        $chunk = $rows.GetRange($i, [Math]::Min(500, $rows.Count - $i))
        [void]$sb.AppendLine("INSERT INTO [$t] (" + ($cols -join ', ') + ') VALUES')
        [void]$sb.AppendLine(($chunk -join ",`n") + ';')
    }
    if ($identity) { [void]$sb.AppendLine("SET IDENTITY_INSERT [$t] OFF;") }
}
[void]$sb.AppendLine('COMMIT TRANSACTION;')
[void]$sb.AppendLine('END')
[void]$sb.AppendLine('GO')
$conn.Close()

# schema first: EF's idempotent migration script creates or upgrades the tables, then the data
Push-Location (Join-Path $root 'backend\EdTechApi.API')
try {
    $schema = Join-Path $env:TEMP 'edtech-schema.sql'
    dotnet ef migrations script --idempotent -o $schema -p ..\EdTechApi.DataAccess\EdTechApi.DataAccess.csproj -s EdTechApi.API.csproj | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'dotnet ef migrations script failed' }
} finally { Pop-Location }

$header = @"
-- E-Kurs: schema and demo data for SQL Server, safe to run more than once.
--   sqlcmd -S localhost\SQLEXPRESS -E -C -Q "CREATE DATABASE EdTechDB"   (if it does not exist)
--   sqlcmd -S localhost\SQLEXPRESS -E -C -d EdTechDB -i database\seed-demo.sql
-- The schema part only applies migrations the database has not seen; the data part is skipped
-- when demo_admin already exists. Running the API in Development seeds the same data itself.
-- sqlcmd starts with QUOTED_IDENTIFIER off; the filtered unique indexes need it on.
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

"@
$utf8 = New-Object System.Text.UTF8Encoding $true
# one batch per migration block: SQL Server compiles a whole batch up front, so a block that uses a
# column an earlier block adds fails on an empty database (the transaction still spans the batches)
$schemaText = [System.IO.File]::ReadAllText($schema) -replace '(?m)^END;\s*$', "END;`nGO"
[System.IO.File]::WriteAllText($Out, $header + $schemaText + "`nGO`n`n" + $sb.ToString(), $utf8)
Write-Host "wrote $Out"
